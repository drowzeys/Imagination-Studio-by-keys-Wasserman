"""Build the optional local zh-TW language pack; --check verifies the committed artifact without writing."""
import argparse, json, re, sys
from pathlib import Path
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("repo", nargs="?", type=Path, default=Path(__file__).resolve().parents[2])
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
repo = args.repo; SEP = "⁣"
dict_, pats, dropped = {}, {}, 0
for en, zh in json.load(open(repo / "tools/i18n-zh/translations.json", encoding="utf8")).items():
        if not zh: continue
        if SEP in en:
            ens, zhs = en.split(SEP), zh.split(SEP)
            if len(ens) != len(zhs): dropped += 1; continue
            # turn the separators into placeholders, numbering after any existing ones
            base = len(re.findall(r"\{\d+(?::\w+)?\}", en)); en2, zh2 = ens[0], zhs[0]
            for i in range(1, len(ens)): en2 += "{%d}" % (base + i - 1) + ens[i]; zh2 += "{%d}" % (base + i - 1) + zhs[i]
            en, zh = re.sub(r"\s+", " ", en2).strip(), re.sub(r"\s+", " ", zh2).strip()
            if not re.search(r"[A-Za-z]{2,}", re.sub(r"\{\d+\}", "", en)): continue
        # named placeholders the code fills with .replace("{where}", ...): number them like the others
        names = [m for m in dict.fromkeys(re.findall(r"\{([a-z_]+)\}", en)) if "{%s}" % m in zh]
        if names:
            base = len(set(re.findall(r"\{\d+(?::\w+)?\}", en)))
            for i, nm in enumerate(names): en = en.replace("{%s}" % nm, "{%d}" % (base + i)); zh = zh.replace("{%s}" % nm, "{%d}" % (base + i))
        # a fragment that opens or closes a bracket the code completes keeps the half-width bracket
        if en.endswith("(") and zh.endswith("（"): zh = zh[:-1] + "("
        if en.startswith(")") and zh.startswith("）"): zh = ")" + zh[1:]
        # a placeholder glued to an English word ("file{1}") is a plural "s": Chinese has none
        for n in re.findall(r"[a-z]\{(\d+)\}(?![A-Za-z])", en): zh = re.sub(r"\s*\{%s\}" % n, "", zh)
        # OSSLab: {0:raw} (shown as it is) and {0:d} (a number only) are placeholders too (i18n.js)
        if re.search(r"\{\d+(?::(?:raw|d))?\}", en):
            if re.fullmatch(r"(\{\d+(?::(?:raw|d))?\}\s*)+", en): continue
            pats[en] = zh
        else:
            dict_[en] = zh
out = repo / "languages/zh-TW.js"
body = ("\"use strict\";\n// Optional Traditional Chinese (Taiwan) UI pack. Generated by tools/i18n-zh/build_dict.py; do not edit.\n"
        "// dict: exact text -> translation. patterns: text with {0}, {1}... standing for values the code fills in.\n"
        "window.STUDIO_ZH = " + json.dumps({"dict": dict_, "patterns": sorted(pats.items())}, ensure_ascii=False, indent=0) + ";\n"
        + (repo / "tools/i18n-zh/overlay.js").read_text("utf8"))
if args.check:
    if not out.is_file() or out.read_bytes() != body.encode("utf8"):
        sys.exit("zh-TW.js is stale: run python3 tools/i18n-zh/build_dict.py")
else:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, "utf8")
print("dict", len(dict_), "patterns", len(pats), "dropped", dropped, "bytes", len(body.encode()))
